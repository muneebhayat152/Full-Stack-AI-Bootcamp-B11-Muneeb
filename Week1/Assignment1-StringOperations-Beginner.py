# Week 1 - Assignment 1: String Operations (Beginner)

# Q1. Length of a string
print(len("hello world"))

# Q2. Uppercase & lowercase
print("Python3".upper())
print("Python3".lower())

# Q3. Count a character
print("banana".count("a"))

# Q4. First & last character
print("First: " + "drawer"[0] + " Last: " + "drawer"[-1])

# Q5. Check substring presence
print("science" in "data science")

# Q6. Slice a string
print("programming"[3:8])

# Q7. Reverse a string
print("Python"[::-1])

# Q8. Replace substring
text = "I love apples. Apples are great!"
print(text.replace("apples", "oranges"))

# Q9. Split and join
text = "split this sentence"
words = text.split()
print("-".join(words))

# Q10. Strip whitespace
text = "   padded text   "
print(text.strip())
