# ==========================================================
# A line that starts with "#" (hash sign) is called a COMMENT.
# A comment is only for humans to read.
# Python completely ignores this line — it does NOT run.
# We write comments to remind ourselves later why we wrote this code.
# ==========================================================

# print() is a FUNCTION.
# A function is a ready-made command that does one specific job.
# The job of the "print" function is: show something on the screen.

# The "( )" right after print are called ROUND BRACKETS (or PARENTHESES).
# Inside these brackets, we tell the function WHAT to show.

# The " " (two straight lines) around Hello, World! are called
# QUOTATION MARKS (or QUOTES).
# Quotes tell Python: "what is inside me is plain TEXT, not a command."
# Anything written inside quotes is called a STRING.

print("Hello, World!")